// Relational or comparison operators

// > - more than
// < - less than
// >= - more than or equal to
// <= - less than or equal to
// == - equal to
// != - not equal to

var result = 10 > 5 // true
console.log(result)

var result = 10 < 5 // false
console.log(result)

var result = 10 >= 10 // true
console.log(result) 

var result = 10 <= 5 // false
console.log(result)

var result = 10 == 10 // true
console.log(result)

var result = 10 != 5 // true
console.log(result)

// equality operators
var x = 1
console.log(x == '1') // true - loose equality - compares values only
console.log(x === '1') // false - strict equality - compares values and types